"""The numbers in the README have to be backed by the files next to them.

A results file and a ledger file can each be perfectly valid and still not
belong together. That is what happened: the ledger published as evidence for
the full model run finished 5,550 seconds before that run started, and the
results file named a third file entirely. Every artefact verified; the claim
that one was evidence for the other did not. FAILURES.md entry 17.

Nothing here calls a model or a network. These are consistency properties of
files already committed, which is exactly the kind of claim that should not
depend on remembering to re-check it.
"""

from __future__ import annotations

import json
from pathlib import Path

import pytest

from parchi.ledger import verify_chain

ROOT = Path(__file__).resolve().parents[1]

PUBLISHED = [
    ("eval/results.json", "the reproducible no-key scoreboard"),
    ("eval/results_model_full.json", "the full model run quoted in the README"),
]


def _load(name: str) -> dict:
    return json.loads((ROOT / name).read_text(encoding="utf-8"))


def _ledger_of(results: dict, what: str) -> Path:
    """The ledger a results file names, or a skip if it is a rebuild artefact.

    `eval/ledger.jsonl` is gitignored: it is regenerated by the scoreboard job
    and is not evidence anybody can check out. The ledgers that ARE committed
    are the ones a reader is invited to verify, and those must hold up. A run
    whose ledger is simply absent gets skipped here rather than asserted about,
    because a checkout is not a failed run.
    """
    path = ROOT / results["ledger"]["path"]
    if not path.exists():
        pytest.skip(f"{what}: {results['ledger']['path']} is regenerated by "
                    "eval/evaluate.py and not committed, so there is nothing "
                    "to check out and verify")
    return path


@pytest.mark.parametrize("name, what", PUBLISHED)
def test_a_published_run_names_the_ledger_it_produced(name, what):
    """The `ledger.path` in a results file must exist and must verify.

    The failure this catches is a results file pointing at a ledger that a
    later run has since overwritten, which is how a scoreboard ends up citing
    someone else's evidence.
    """
    results = _load(name)
    ledger_path = _ledger_of(results, what)

    ok, detail, records = verify_chain(str(ledger_path))
    assert ok, f"{what}: {detail}"
    assert records == results["ledger"]["records"], (
        f"{what}: claims {results['ledger']['records']} records, "
        f"the file has {records}")
    assert records == results["dataset"]["rows"], (
        f"{what}: scored {results['dataset']['rows']} rows but the ledger "
        f"holds {records}")


@pytest.mark.parametrize("name, what", PUBLISHED)
def test_the_ledger_was_written_during_the_run_that_reports_it(name, what):
    """Three timestamps that have to nest, and once did not.

    A run writes its ledger as it goes and its results file at the end, so
    every ledger record must land inside the window
    `[generated_at - seconds, generated_at]`. A ledger from an earlier run
    fails this by a wide margin: the one that prompted this test missed by
    over an hour.
    """
    results = _load(name)
    generated_at = results["generated_at"]
    took = results["approaches"]["parchi"]["run"]["seconds"]
    started = generated_at - took

    ledger_path = _ledger_of(results, what)
    lines = [ln for ln in ledger_path.read_text(encoding="utf-8").splitlines() if ln.strip()]
    first = json.loads(lines[0])["ts"] / 1000
    last = json.loads(lines[-1])["ts"] / 1000

    # A minute of slack each side: the run block times the scored pass, while
    # the file also carries the warm-up and the write itself.
    assert started - 60 <= first, (
        f"{what}: the ledger starts {started - first:.0f}s before the run did, "
        f"so it is a ledger from an earlier run")
    assert last <= generated_at + 60, (
        f"{what}: the ledger ends {last - generated_at:.0f}s after the results "
        f"were written")


@pytest.mark.parametrize("name, what", PUBLISHED)
def test_a_published_run_says_what_produced_it(name, what):
    """A number nobody can attribute is a number nobody can reproduce."""
    results = _load(name)
    assert results.get("intent_provider"), f"{what}: no provider recorded"
    assert results.get("intent_timeout_seconds"), f"{what}: no timeout recorded"
    if results["intent_provider"] not in ("heuristic", "off"):
        assert results.get("intent_model"), (
            f"{what}: a model run that does not record which model")


@pytest.mark.parametrize("name, what", PUBLISHED)
def test_the_named_ledger_path_is_posix_and_inside_eval(name, what):
    r"""Checked even when the file itself is a rebuild artefact.

    The results file that started this recorded `eval\ledger.jsonl`, with a
    Windows separator, which is both the wrong file and a path no reader on
    another platform could follow.
    """
    named = _load(name)["ledger"]["path"]
    assert "\\" not in named, f"{what}: platform separator in a published path"
    assert named.startswith("eval/"), f"{what}: ledger published outside eval/"


def test_the_two_published_runs_do_not_share_a_ledger():
    """Two runs citing one file means at least one of them is citing the wrong
    one, since a full run overwrites whatever ledger it was given."""
    paths = {_load(name)["ledger"]["path"] for name, _ in PUBLISHED}
    assert len(paths) == len(PUBLISHED), f"published runs share a ledger: {paths}"


def test_the_readme_quotes_the_model_run_it_links():
    """The headline model figure in the README is the one in the results file.

    Read out of the file rather than retyped, because the number in prose and
    the number in the artefact drifting apart is the same class of failure as
    the ledger drifting from the results.
    """
    results = _load("eval/results_model_full.json")
    metrics = results["approaches"]["parchi"]["metrics"]
    caught, total = metrics["tp"], metrics["tp"] + metrics["fn"]
    readme = (ROOT / "README.md").read_text(encoding="utf-8")
    claim = f"{caught}/{total} ({metrics['recall'] * 100:.1f}%)"
    assert claim in readme, (
        f"README does not quote the model run's own figure {claim}; "
        "either the run was re-done and the prose was not, or the other way round")
    assert f"| {metrics['fp']} | {results['approaches']['parchi']['run']['degraded_rows']} |" in readme, (
        "README's false-block and degraded columns do not match the results file")


